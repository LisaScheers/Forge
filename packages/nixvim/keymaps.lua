local dap, dapui = require("dap"), require("dapui")
dap.listeners.after.event_initialized["forge_ui"] = function()
  dapui.open()
end
dap.listeners.before.event_terminated["forge_ui"] = function()
  dapui.close()
end
dap.listeners.before.event_exited["forge_ui"] = function()
  dapui.close()
end

